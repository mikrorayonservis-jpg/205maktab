-- 0002_identity_and_auth.sql
-- Rollar, icazələr, istifadəçilər və autentifikasiya təhlükəsizliyi cədvəlləri.
-- Mənbə: MySQL miqrasiyaları 001, 008 (sessions, password_resets), 009.
--
-- Bayraq sütunları (is_active, email_verified, ...) tətbiq kodu ilə uyğunluq üçün SMALLINT 0/1
-- kimi saxlanılır (CHECK ilə məhdudlaşdırılıb). Rolların siyahısı src/config/rbac.json-dan
-- `npm run db:migrate` (və ya seed.sql) ilə sinxronlaşdırılır.

CREATE TABLE public.roles (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code            varchar(50)  NOT NULL UNIQUE,
  name_az         varchar(100) NOT NULL,
  description_az  varchar(255),
  created_at      timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE public.permissions (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        varchar(100) NOT NULL UNIQUE,
  name_az     varchar(150) NOT NULL,
  module      varchar(50)  NOT NULL DEFAULT 'general',
  created_at  timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE public.role_permissions (
  role_id        integer     NOT NULL REFERENCES public.roles(id) ON DELETE CASCADE,
  permission_id  integer     NOT NULL REFERENCES public.permissions(id) ON DELETE CASCADE,
  created_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (role_id, permission_id)
);
CREATE INDEX idx_role_permissions_permission ON public.role_permissions (permission_id);

CREATE TABLE public.users (
  id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email                 varchar(190) NOT NULL UNIQUE CHECK (email = lower(email)),
  first_name            varchar(100),
  last_name             varchar(100),
  phone_private         varchar(30),
  avatar_url            varchar(500),
  password_hash         varchar(255) NOT NULL,
  role                  varchar(50)  NOT NULL DEFAULT 'student',
  is_active             smallint     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  email_verified        smallint     NOT NULL DEFAULT 0 CHECK (email_verified IN (0, 1)),
  email_verified_at     timestamptz,
  failed_login_count    integer      NOT NULL DEFAULT 0 CHECK (failed_login_count >= 0),
  locked_until          timestamptz,
  password_changed_at   timestamptz,
  must_change_password  smallint     NOT NULL DEFAULT 0 CHECK (must_change_password IN (0, 1)),
  last_login_at         timestamptz,
  created_at            timestamptz  NOT NULL DEFAULT now(),
  updated_at            timestamptz  NOT NULL DEFAULT now(),
  deleted_at            timestamptz
);
COMMENT ON COLUMN public.users.role IS 'Əsas rolun keşi; həqiqət mənbəyi user_roles cədvəlidir';
CREATE INDEX idx_users_role ON public.users (role);
CREATE INDEX idx_users_active ON public.users (is_active);

CREATE TABLE public.user_roles (
  user_id      integer     NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  role_id      integer     NOT NULL REFERENCES public.roles(id) ON DELETE CASCADE,
  assigned_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, role_id)
);
CREATE INDEX idx_user_roles_role ON public.user_roles (role_id);

-- Server sessiyaları: cookie-də yalnız təsadüfi token, burada onun SHA-256 hash-i
CREATE TABLE public.sessions (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       integer      NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  token_hash    varchar(128) NOT NULL UNIQUE,
  expires_at    timestamptz  NOT NULL,
  ip_address    varchar(45),
  user_agent    varchar(400),
  last_seen_at  timestamptz,
  revoked_at    timestamptz,
  created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_sessions_user ON public.sessions (user_id);
CREATE INDEX idx_sessions_expires ON public.sessions (expires_at);

-- Parol bərpası: token sütununda tokenin SHA-256 hash-i saxlanılır
CREATE TABLE public.password_resets (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer      NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  token       varchar(100) NOT NULL UNIQUE,
  expires_at  timestamptz  NOT NULL,
  used        smallint     NOT NULL DEFAULT 0 CHECK (used IN (0, 1)),
  used_at     timestamptz,
  ip_address  varchar(45),
  created_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_password_resets_user ON public.password_resets (user_id);
CREATE INDEX idx_password_resets_expires ON public.password_resets (expires_at);

CREATE TABLE public.email_verifications (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer     NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  token_hash  char(64)    NOT NULL UNIQUE,
  expires_at  timestamptz NOT NULL,
  used_at     timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_email_verifications_user ON public.email_verifications (user_id);

-- Giriş cəhdləri jurnalı (user_id qəsdən FK deyil: silinmiş istifadəçinin izi qalır)
CREATE TABLE public.login_attempts (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       varchar(190) NOT NULL,
  user_id     integer,
  ip_address  varchar(45),
  user_agent  varchar(400),
  success     smallint     NOT NULL CHECK (success IN (0, 1)),
  reason      varchar(50),
  created_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_login_attempts_email ON public.login_attempts (email, created_at);
CREATE INDEX idx_login_attempts_ip ON public.login_attempts (ip_address, created_at);
CREATE INDEX idx_login_attempts_user ON public.login_attempts (user_id);

-- Sabit pəncərəli rate limit (bir neçə server instansiyası arasında paylaşılır)
CREATE TABLE public.rate_limits (
  bucket_key    varchar(191) PRIMARY KEY,
  window_start  timestamptz  NOT NULL,
  hits          integer      NOT NULL DEFAULT 0 CHECK (hits >= 0)
);
