-- Tədris illəri, fənlər, müəllimlər, siniflər, şagirdlər, valideynlər, təyinatlar, zəng cədvəli, dəvətlər.
-- Mənbə: MySQL miqrasiyaları 002, 003, 009 (invitations), 010, 011 (bell_times).
--
-- Məxfilik: teachers.phone_private / address_private və users.phone_private heç vaxt ictimai
-- sorğulara daxil edilmir (src/server/content.ts). Şagirdlərin ictimai profili yoxdur.

CREATE TABLE public.school_years (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        varchar(20) NOT NULL UNIQUE,
  start_date  date        NOT NULL,
  end_date    date        NOT NULL,
  is_active   smallint    NOT NULL DEFAULT 0 CHECK (is_active IN (0, 1)),
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_school_years_range CHECK (end_date > start_date)
);
CREATE INDEX idx_school_years_active ON public.school_years (is_active);

CREATE TABLE public.subjects (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        varchar(20)  NOT NULL UNIQUE,
  name_az     varchar(100) NOT NULL,
  created_at  timestamptz  NOT NULL DEFAULT now()
);

-- Müəllim profili hesabsız da mövcud ola bilər (user_id NULL) — dəvət kodu ilə sonradan bağlanır
CREATE TABLE public.teachers (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           integer UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
  employee_code     varchar(30)  NOT NULL UNIQUE,
  first_name        varchar(100) NOT NULL,
  last_name         varchar(100) NOT NULL,
  subject           varchar(100),
  position_az       varchar(150),
  education_az      varchar(500),
  qualification     varchar(255),
  experience_years  integer DEFAULT 0 CHECK (experience_years IS NULL OR experience_years >= 0),
  bio               text,
  phone_private     varchar(30),
  address_private   text,
  is_public         smallint NOT NULL DEFAULT 1 CHECK (is_public IN (0, 1)),
  sort_order        integer  NOT NULL DEFAULT 0,
  is_active         smallint NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  avatar_url        varchar(500),
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  deleted_at        timestamptz
);
COMMENT ON COLUMN public.teachers.phone_private IS 'Məxfi: heç vaxt ictimai göstərilmir';
COMMENT ON COLUMN public.teachers.address_private IS 'Məxfi: heç vaxt ictimai göstərilmir';
CREATE INDEX idx_teachers_subject ON public.teachers (subject);
CREATE INDEX idx_teachers_public ON public.teachers (is_public, is_active);

CREATE TABLE public.classes (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              varchar(20) NOT NULL,
  grade_level       smallint    NOT NULL CHECK (grade_level BETWEEN 0 AND 12),
  school_year_id    integer     NOT NULL REFERENCES public.school_years(id) ON DELETE CASCADE,
  room              varchar(20),
  class_teacher_id  integer REFERENCES public.teachers(id) ON DELETE SET NULL,
  shift             smallint    NOT NULL DEFAULT 1 CHECK (shift BETWEEN 1 AND 3),
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_classes_name_year UNIQUE (name, school_year_id)
);
CREATE INDEX idx_classes_year ON public.classes (school_year_id);
CREATE INDEX idx_classes_class_teacher ON public.classes (class_teacher_id);

-- Şagird profili hesabsız da mövcud ola bilər (user_id NULL)
CREATE TABLE public.students (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         integer UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
  student_code    varchar(30)  NOT NULL UNIQUE,
  first_name      varchar(100) NOT NULL,
  last_name       varchar(100) NOT NULL,
  class_id        integer REFERENCES public.classes(id) ON DELETE SET NULL,
  school_year_id  integer REFERENCES public.school_years(id) ON DELETE SET NULL,
  avatar_url      varchar(500),
  is_public       smallint NOT NULL DEFAULT 0 CHECK (is_public IN (0, 1)),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  deleted_at      timestamptz
);
COMMENT ON TABLE public.students IS 'Azyaşlıların şəxsi məlumatları: ictimai görünmür';
CREATE INDEX idx_students_class ON public.students (class_id);

CREATE TABLE public.parents (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer      NOT NULL UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
  first_name  varchar(100) NOT NULL,
  last_name   varchar(100) NOT NULL,
  email       varchar(190) NOT NULL UNIQUE CHECK (email = lower(email)),
  phone       varchar(30),
  created_at  timestamptz  NOT NULL DEFAULT now(),
  updated_at  timestamptz  NOT NULL DEFAULT now(),
  deleted_at  timestamptz
);

-- Valideyn ↔ şagird əlaqəsi: valideynin görə biləcəyi yeganə şagirdlər
CREATE TABLE public.parent_student (
  parent_id      integer     NOT NULL REFERENCES public.parents(id) ON DELETE CASCADE,
  student_id     integer     NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  relation_type  varchar(50) DEFAULT 'valideyn',
  created_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (parent_id, student_id)
);
CREATE INDEX idx_parent_student_student ON public.parent_student (student_id);

-- Müəllim təyinatı (sinif + fənn + tədris ili): müəllim icazələrinin əsası
CREATE TABLE public.class_subjects (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id        integer NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  subject_id      integer NOT NULL REFERENCES public.subjects(id) ON DELETE CASCADE,
  teacher_id      integer REFERENCES public.teachers(id) ON DELETE SET NULL,
  school_year_id  integer NOT NULL REFERENCES public.school_years(id) ON DELETE CASCADE,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_class_subjects UNIQUE (class_id, subject_id, school_year_id)
);
CREATE INDEX idx_class_subjects_teacher ON public.class_subjects (teacher_id, school_year_id);
CREATE INDEX idx_class_subjects_subject ON public.class_subjects (subject_id);

-- Sinif üzvlüyü tarixçəsi
CREATE TABLE public.class_students (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id        integer NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  student_id      integer NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  school_year_id  integer NOT NULL REFERENCES public.school_years(id) ON DELETE CASCADE,
  enrolled_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_class_students UNIQUE (class_id, student_id, school_year_id)
);
CREATE INDEX idx_class_students_student ON public.class_students (student_id);

CREATE TABLE public.bell_times (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift       smallint NOT NULL DEFAULT 1 CHECK (shift BETWEEN 1 AND 3),
  period      smallint NOT NULL CHECK (period BETWEEN 1 AND 12),
  start_time  time     NOT NULL,
  end_time    time     NOT NULL,
  CONSTRAINT uq_bell_times UNIQUE (shift, period),
  CONSTRAINT chk_bell_times_range CHECK (end_time > start_time)
);

-- Dəvət kodları: yalnız SHA-256 hash saxlanılır; kod bir dəfə göstərilir
CREATE TABLE public.invitations (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code_hash      char(64)     NOT NULL UNIQUE,
  code_hint      varchar(8)   NOT NULL,
  role_code      varchar(50)  NOT NULL,
  email          varchar(190) CHECK (email IS NULL OR email = lower(email)),
  student_id     integer REFERENCES public.students(id) ON DELETE CASCADE,
  teacher_id     integer REFERENCES public.teachers(id) ON DELETE CASCADE,
  relation_type  varchar(50),
  expires_at     timestamptz  NOT NULL,
  used_at        timestamptz,
  used_by        integer REFERENCES public.users(id) ON DELETE SET NULL,
  revoked_at     timestamptz,
  created_by     integer      NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at     timestamptz  NOT NULL DEFAULT now()
);
COMMENT ON COLUMN public.invitations.code_hint IS 'Kodun son 4 simvolu (admin üçün)';
CREATE INDEX idx_invitations_student ON public.invitations (student_id);
CREATE INDEX idx_invitations_teacher ON public.invitations (teacher_id);
