CREATE TABLE public.lessons (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id        integer  NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  subject_id      integer  NOT NULL REFERENCES public.subjects(id) ON DELETE CASCADE,
  teacher_id      integer  NOT NULL REFERENCES public.teachers(id) ON DELETE CASCADE,
  school_year_id  integer  NOT NULL REFERENCES public.school_years(id) ON DELETE CASCADE,
  day_of_week     smallint NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
  period          smallint NOT NULL CHECK (period BETWEEN 1 AND 12),
  start_time      time     NOT NULL,
  end_time        time     NOT NULL,
  room            varchar(20),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_lessons_class_period UNIQUE (class_id, day_of_week, period, school_year_id),
  CONSTRAINT chk_lessons_range CHECK (end_time > start_time)
);
COMMENT ON COLUMN public.lessons.day_of_week IS '1 = Bazar ertəsi ... 7 = Bazar';
CREATE INDEX idx_lessons_teacher_day ON public.lessons (teacher_id, day_of_week);
CREATE INDEX idx_lessons_class_day ON public.lessons (class_id, day_of_week);
CREATE INDEX idx_lessons_year_day ON public.lessons (school_year_id, day_of_week);
CREATE INDEX idx_lessons_subject ON public.lessons (subject_id);

-- Azərbaycan qiymətləndirmə sistemi: 2–5 şkalası
CREATE TABLE public.grades (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id      integer  NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  subject_id      integer  NOT NULL REFERENCES public.subjects(id) ON DELETE CASCADE,
  teacher_id      integer  NOT NULL REFERENCES public.teachers(id) ON DELETE CASCADE,
  class_id        integer  NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  school_year_id  integer REFERENCES public.school_years(id) ON DELETE SET NULL,
  grade_type      varchar(20) NOT NULL DEFAULT 'formativ'
                  CHECK (grade_type IN ('formativ', 'ksq', 'bsq', 'ev', 'layihe', 'yekun')),
  grade_value     smallint NOT NULL CHECK (grade_value BETWEEN 2 AND 5),
  date            date     NOT NULL,
  note            varchar(255),
  created_by      integer REFERENCES public.users(id) ON DELETE SET NULL,
  updated_by      integer REFERENCES public.users(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  deleted_at      timestamptz
);
CREATE INDEX idx_grades_student ON public.grades (student_id, school_year_id);
CREATE INDEX idx_grades_class_subject_date ON public.grades (class_id, subject_id, date);
CREATE INDEX idx_grades_teacher ON public.grades (teacher_id);
CREATE INDEX idx_grades_subject ON public.grades (subject_id);
CREATE INDEX idx_grades_year ON public.grades (school_year_id);

-- period = 0 gündəlik davamiyyət (sinif rəhbəri), 1..8 dərs üzrə (dərsin müəllimi)
CREATE TABLE public.attendance (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id  integer  NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  lesson_id   integer REFERENCES public.lessons(id) ON DELETE SET NULL,
  class_id    integer  NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  date        date     NOT NULL,
  period      smallint NOT NULL DEFAULT 0 CHECK (period BETWEEN 0 AND 12),
  subject_id  integer REFERENCES public.subjects(id) ON DELETE SET NULL,
  status      varchar(20) NOT NULL DEFAULT 'present'
              CHECK (status IN ('present', 'late', 'excused', 'unexcused')),
  marked_by   integer  NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  note        varchar(255),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_attendance_student_date_period UNIQUE (student_id, date, period)
);
CREATE INDEX idx_attendance_class_date ON public.attendance (class_id, date);
CREATE INDEX idx_attendance_date_status ON public.attendance (date, status);
CREATE INDEX idx_attendance_lesson ON public.attendance (lesson_id);
CREATE INDEX idx_attendance_marked_by ON public.attendance (marked_by);

-- Yüklənmiş fayllar (məzmun Supabase Storage-də və ya lokal storage/ qovluğunda)
CREATE TABLE public.files (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  storage_key    varchar(255) NOT NULL UNIQUE,
  original_name  varchar(255) NOT NULL,
  mime_type      varchar(100) NOT NULL,
  size_bytes     integer      NOT NULL CHECK (size_bytes >= 0),
  width          integer CHECK (width IS NULL OR width >= 0),
  height         integer CHECK (height IS NULL OR height >= 0),
  visibility     varchar(10)  NOT NULL DEFAULT 'private' CHECK (visibility IN ('public', 'private')),
  purpose        varchar(50)  NOT NULL,
  owner_user_id  integer REFERENCES public.users(id) ON DELETE SET NULL,
  created_at     timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT chk_files_key_visibility CHECK (storage_key LIKE visibility || '/%')
);
COMMENT ON COLUMN public.files.purpose IS 'news, gallery, document, homework, submission, avatar, content';
CREATE INDEX idx_files_owner ON public.files (owner_user_id);

CREATE TABLE public.homework (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title           varchar(255) NOT NULL,
  description     text,
  subject_id      integer NOT NULL REFERENCES public.subjects(id) ON DELETE CASCADE,
  class_id        integer NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  teacher_id      integer NOT NULL REFERENCES public.teachers(id) ON DELETE CASCADE,
  school_year_id  integer REFERENCES public.school_years(id) ON DELETE SET NULL,
  due_date        date    NOT NULL,
  file_url        varchar(500),
  created_by      integer REFERENCES public.users(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  deleted_at      timestamptz
);
CREATE INDEX idx_homework_class_due ON public.homework (class_id, due_date);
CREATE INDEX idx_homework_teacher ON public.homework (teacher_id);
CREATE INDEX idx_homework_subject ON public.homework (subject_id);

CREATE TABLE public.homework_files (
  homework_id  integer NOT NULL REFERENCES public.homework(id) ON DELETE CASCADE,
  file_id      integer NOT NULL REFERENCES public.files(id) ON DELETE CASCADE,
  PRIMARY KEY (homework_id, file_id)
);
CREATE INDEX idx_homework_files_file ON public.homework_files (file_id);

CREATE TABLE public.homework_submissions (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  homework_id   integer NOT NULL REFERENCES public.homework(id) ON DELETE CASCADE,
  student_id    integer NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  answer_text   text,
  file_url      varchar(500),
  file_id       integer REFERENCES public.files(id) ON DELETE SET NULL,
  status        varchar(20) NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'graded', 'returned')),
  submitted_at  timestamptz NOT NULL DEFAULT now(),
  grade         numeric(4,2) CHECK (grade IS NULL OR grade BETWEEN 2 AND 5),
  feedback      text,
  graded_by     integer REFERENCES public.teachers(id) ON DELETE SET NULL,
  graded_at     timestamptz,
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_submissions_homework_student UNIQUE (homework_id, student_id)
);
CREATE INDEX idx_submissions_student ON public.homework_submissions (student_id);
CREATE INDEX idx_submissions_file ON public.homework_submissions (file_id);
