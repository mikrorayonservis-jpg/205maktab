-- 0005_newsroom_and_media.sql
-- Xəbər redaksiyası, tədbirlər, qalereya, sənədlər və saytın statik məzmunu.
-- Mənbə: MySQL miqrasiyaları 006, 007, 010 (leadership, achievements, useful_links, pages), 012.
--
-- Azyaşlıların qorunması: contains_minors = 1 olan xəbər/albom yalnız consent_confirmed = 1 olduqda
-- dərc edilir (server tərəfində yoxlanılır) və ictimai sorğular bu şərti həmişə əlavə edir.

CREATE TABLE public.news_categories (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_az         varchar(150) NOT NULL,
  slug            varchar(190) NOT NULL UNIQUE,
  description_az  text,
  created_at      timestamptz  NOT NULL DEFAULT now()
);

-- v1-dən qalmış müəllif cədvəli (v2 kodunda istifadə olunmur; mövcud məlumatın itməməsi üçün saxlanılır)
CREATE TABLE public.news_authors (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_az     varchar(150) NOT NULL,
  email       varchar(190) UNIQUE,
  bio_az      text,
  avatar_url  varchar(500),
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.galleries (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title_az           varchar(255) NOT NULL,
  slug               varchar(255) NOT NULL UNIQUE,
  description_az     text,
  category_az        varchar(100),
  cover_image        varchar(500),
  event_date         date,
  contains_minors    smallint NOT NULL DEFAULT 0 CHECK (contains_minors IN (0, 1)),
  consent_confirmed  smallint NOT NULL DEFAULT 0 CHECK (consent_confirmed IN (0, 1)),
  is_published       smallint NOT NULL DEFAULT 0 CHECK (is_published IN (0, 1)),
  created_by         integer  NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  deleted_at         timestamptz
);
CREATE INDEX idx_galleries_public ON public.galleries (is_published, event_date);

CREATE TABLE public.news (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title_az            varchar(300) NOT NULL,
  slug                varchar(300) NOT NULL UNIQUE,
  summary_az          text,
  content_az          text NOT NULL,
  cover_image         varchar(500),
  cover_alt_az        varchar(255),
  category_id         integer REFERENCES public.news_categories(id) ON DELETE SET NULL,
  author_id           integer REFERENCES public.news_authors(id) ON DELETE CASCADE,
  byline_az           varchar(200),
  created_by          integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  status              varchar(20) NOT NULL DEFAULT 'draft'
                      CHECK (status IN ('draft', 'pending', 'approved', 'published', 'archived')),
  is_featured         smallint NOT NULL DEFAULT 0 CHECK (is_featured IN (0, 1)),
  contains_minors     smallint NOT NULL DEFAULT 0 CHECK (contains_minors IN (0, 1)),
  consent_confirmed   smallint NOT NULL DEFAULT 0 CHECK (consent_confirmed IN (0, 1)),
  review_note         text,
  submitted_at        timestamptz,
  approved_by         integer REFERENCES public.users(id) ON DELETE SET NULL,
  published_by        integer REFERENCES public.users(id) ON DELETE SET NULL,
  gallery_id          integer REFERENCES public.galleries(id) ON DELETE SET NULL,
  seo_title_az        varchar(300),
  seo_description_az  text,
  views               integer NOT NULL DEFAULT 0 CHECK (views >= 0),
  published_at        timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  deleted_at          timestamptz
);
COMMENT ON COLUMN public.news.created_by IS 'users.id — məqaləni yaradan';
CREATE INDEX idx_news_public ON public.news (status, deleted_at, published_at);
CREATE INDEX idx_news_category ON public.news (category_id);
CREATE INDEX idx_news_created_by ON public.news (created_by);
CREATE INDEX idx_news_updated ON public.news (updated_at);

CREATE TABLE public.news_revisions (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  news_id        integer NOT NULL REFERENCES public.news(id) ON DELETE CASCADE,
  action         varchar(40) NOT NULL DEFAULT 'edit',
  status_from    varchar(20),
  status_to      varchar(20),
  title_az       varchar(300),
  content_az     text,
  summary_az     text,
  change_reason  varchar(255),
  changed_by     integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_news_revisions_news ON public.news_revisions (news_id);

-- Tədbir vaxtları Bakı yerli vaxtı ilə (saat qurşağısız) saxlanılır — MySQL DATETIME ekvivalenti
CREATE TABLE public.events (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title_az         varchar(300) NOT NULL,
  slug             varchar(300) NOT NULL UNIQUE,
  description_az   text,
  start_datetime   timestamp(0) NOT NULL,
  end_datetime     timestamp(0),
  location_az      varchar(255),
  participants_az  text,
  cover_image      varchar(500),
  gallery_id       integer REFERENCES public.galleries(id) ON DELETE SET NULL,
  status           varchar(20) NOT NULL DEFAULT 'planned'
                   CHECK (status IN ('planned', 'ongoing', 'completed', 'cancelled')),
  is_published     smallint NOT NULL DEFAULT 1 CHECK (is_published IN (0, 1)),
  created_by       integer  NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  deleted_at       timestamptz,
  CONSTRAINT chk_events_range CHECK (end_datetime IS NULL OR end_datetime >= start_datetime)
);
CREATE INDEX idx_events_start ON public.events (start_datetime);
CREATE INDEX idx_events_status ON public.events (status);

CREATE TABLE public.gallery_images (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gallery_id  integer NOT NULL REFERENCES public.galleries(id) ON DELETE CASCADE,
  image_url   varchar(500) NOT NULL,
  file_id     integer REFERENCES public.files(id) ON DELETE SET NULL,
  caption_az  varchar(255),
  alt_text    varchar(255),
  taken_at    date,
  sort_order  integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_gallery_images_gallery ON public.gallery_images (gallery_id, sort_order);
CREATE INDEX idx_gallery_images_file ON public.gallery_images (file_id);

CREATE TABLE public.gallery_videos (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gallery_id  integer NOT NULL REFERENCES public.galleries(id) ON DELETE CASCADE,
  title_az    varchar(255),
  provider    varchar(10) NOT NULL CHECK (provider IN ('youtube', 'vimeo')),
  video_id    varchar(64) NOT NULL,
  sort_order  integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_gallery_videos_gallery ON public.gallery_videos (gallery_id, sort_order);

CREATE TABLE public.documents (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title_az        varchar(300) NOT NULL,
  slug            varchar(300) NOT NULL UNIQUE,
  category_az     varchar(100) NOT NULL,
  description_az  text,
  file_url        varchar(500) NOT NULL,
  file_id         integer REFERENCES public.files(id) ON DELETE SET NULL,
  file_type       varchar(50),
  file_size       integer CHECK (file_size IS NULL OR file_size >= 0),
  uploaded_by     integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  is_public       smallint NOT NULL DEFAULT 1 CHECK (is_public IN (0, 1)),
  published_on    date,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  deleted_at      timestamptz
);
CREATE INDEX idx_documents_category ON public.documents (category_az);
CREATE INDEX idx_documents_public ON public.documents (is_public);
CREATE INDEX idx_documents_file ON public.documents (file_id);

CREATE TABLE public.leadership (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name           varchar(200) NOT NULL,
  position_az         varchar(200) NOT NULL,
  photo_url           varchar(500),
  bio_az              text,
  education_az        varchar(500),
  experience_az       varchar(500),
  message_az          text,
  reception_hours_az  varchar(200),
  is_director         smallint NOT NULL DEFAULT 0 CHECK (is_director IN (0, 1)),
  sort_order          integer  NOT NULL DEFAULT 0,
  is_published        smallint NOT NULL DEFAULT 1 CHECK (is_published IN (0, 1)),
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_leadership_order ON public.leadership (is_published, sort_order);

CREATE TABLE public.achievements (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title_az        varchar(255) NOT NULL,
  description_az  text,
  year_label      varchar(20),
  image_url       varchar(500),
  sort_order      integer  NOT NULL DEFAULT 0,
  is_published    smallint NOT NULL DEFAULT 1 CHECK (is_published IN (0, 1)),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.useful_links (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title_az      varchar(200) NOT NULL,
  url           varchar(500) NOT NULL,
  sort_order    integer  NOT NULL DEFAULT 0,
  is_published  smallint NOT NULL DEFAULT 1 CHECK (is_published IN (0, 1)),
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- Statik səhifələr (Markdown)
CREATE TABLE public.pages (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug        varchar(100) NOT NULL UNIQUE,
  title_az    varchar(255) NOT NULL,
  content_md  text NOT NULL,
  updated_by  integer REFERENCES public.users(id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
