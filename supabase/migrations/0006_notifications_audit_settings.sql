CREATE TABLE public.notifications (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      integer      NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  title_az     varchar(255) NOT NULL,
  message_az   text,
  type         varchar(50)  DEFAULT 'info',
  link_url     varchar(500),
  entity_type  varchar(50),
  entity_id    integer,
  is_read      smallint     NOT NULL DEFAULT 0 CHECK (is_read IN (0, 1)),
  read_at      timestamptz,
  created_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_notifications_user_unread ON public.notifications (user_id, is_read);
CREATE INDEX idx_notifications_dedupe ON public.notifications (user_id, entity_type, entity_id, type);

-- Audit jurnalı: kim, nə vaxt, hansı obyektdə nəyi dəyişdi (parol/token sahələri tətbiqdə çıxarılır)
CREATE TABLE public.audit_logs (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      integer REFERENCES public.users(id) ON DELETE SET NULL,
  action       varchar(100) NOT NULL,
  entity_type  varchar(100) NOT NULL,
  entity_id    bigint,
  old_values   jsonb,
  new_values   jsonb,
  ip_address   varchar(45),
  user_agent   text,
  created_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_user_action ON public.audit_logs (user_id, action);
CREATE INDEX idx_audit_entity ON public.audit_logs (entity_type, entity_id);
CREATE INDEX idx_audit_created ON public.audit_logs (created_at);

CREATE TABLE public.site_settings (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  setting_key     varchar(100) NOT NULL UNIQUE,
  setting_value   text,
  description_az  varchar(255),
  updated_by      integer REFERENCES public.users(id) ON DELETE SET NULL,
  updated_at      timestamptz  NOT NULL DEFAULT now()
);
