-- 0009_class_invite_codes.sql
-- Sinif dəvət kodları: şagird qeydiyyatda kodu yazır, server kodu yoxlayıb onu həmin sinfə yerləşdirir.
--
-- Fərdi dəvətlərdən (invitations, yalnız hash) fərqli olaraq sinif kodu çoxdəfəlikdir və administrator onu
-- istənilən vaxt yenidən görüb kopyalaya bilməlidir — ona görə kodun özü saxlanılır. Kodlar audit jurnalına
-- və server loglarına yazılmır (yalnız son 4 simvol). Data API bağlıdır (RLS, policy yoxdur).
--
-- Geri qaytarma (yalnız lazım olarsa, əl ilə):
--   DROP TABLE public.class_invite_codes; ALTER TABLE public.classes DROP COLUMN is_active;
--   DROP INDEX public.idx_students_name;

-- Sinfin aktivlik statusu (deaktiv sinfə kodla qoşulmaq olmur; mövcud qeydlər toxunulmaz qalır)
ALTER TABLE public.classes
  ADD COLUMN is_active smallint NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1));

CREATE TABLE public.class_invite_codes (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id    integer     NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  code        varchar(32) NOT NULL,
  code_norm   varchar(32) NOT NULL UNIQUE,
  is_active   smallint    NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  max_uses    integer     CHECK (max_uses IS NULL OR max_uses > 0),
  use_count   integer     NOT NULL DEFAULT 0 CHECK (use_count >= 0),
  expires_at  timestamptz,
  created_by  integer REFERENCES public.users(id) ON DELETE SET NULL,
  updated_by  integer REFERENCES public.users(id) ON DELETE SET NULL,
  revoked_at  timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.class_invite_codes IS 'Sinif dəvət kodları; revoked_at IS NULL olan yeganə sətir sinfin cari kodudur';
COMMENT ON COLUMN public.class_invite_codes.code_norm IS 'Böyük hərf, yalnız A-Z0-9 (axtarış üçün)';

-- Hər sinfin ən çox bir cari (ləğv edilməmiş) kodu ola bilər; köhnə kodlar tarixçə üçün qalır
CREATE UNIQUE INDEX uq_class_invite_codes_current ON public.class_invite_codes (class_id) WHERE revoked_at IS NULL;

CREATE TRIGGER trg_class_invite_codes_updated_at BEFORE UPDATE ON public.class_invite_codes
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.class_invite_codes ENABLE ROW LEVEL SECURITY;

-- Toplu import və təkrar qeydlərin aşkarlanması üçün ad üzrə axtarış
CREATE INDEX idx_students_name ON public.students (lower(last_name), lower(first_name));
